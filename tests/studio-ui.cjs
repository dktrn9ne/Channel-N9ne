// Run after `npm install --no-save playwright`. Requires Chromium and ffmpeg.
const { chromium } = require('playwright');
const { spawn, execFileSync } = require('node:child_process');
const { mkdtempSync, writeFileSync, mkdirSync, readFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve } = require('node:path');
const assert = require('node:assert/strict');
const root = resolve(__dirname, '..');
const temp = mkdtempSync(join(tmpdir(), 'n9ne-studio-ui-'));
const screenshots = process.env.STUDIO_QA_DIR || temp;
mkdirSync(screenshots, { recursive: true });
const port = Number(process.env.STUDIO_TEST_PORT || 8877);
const server = spawn('python3', ['-m', 'http.server', String(port), '--bind', '127.0.0.1'], { cwd: root, stdio: 'ignore' });
let browser;
(async () => {
  const video = join(temp, 'recording.mp4');
  execFileSync('ffmpeg', ['-v','error','-f','lavfi','-i','color=c=navy:s=320x180:r=10','-t','360','-c:v','libx264','-pix_fmt','yuv420p',video]);
  const transcript = join(temp, 'moments.vtt');
  writeFileSync(transcript, 'WEBVTT\n\n' + Array.from({length:5}, (_, i) => {
    const start=i*70+2,end=start+8;
    const time = n => `00:${String(Math.floor(n/60)).padStart(2,'0')}:${String(n%60).padStart(2,'0')}.000`;
    return `${time(start)} --> ${time(end)}\nAmazing! Here is why this works. Watch this incredible moment ${i+1}!\n`;
  }).join('\n'));
  writeFileSync(join(temp,'bad.vtt'), 'WEBVTT\n\n00:00:05.000 --> 00:00:01.000\nInvalid backwards cue');
  writeFileSync(join(temp,'bad.mp4'), 'not a recording');
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const errors = [];
  await page.route('**/api/studio?session=1', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({authenticated:true}) }));
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  for (let attempt=0; attempt<30; attempt++) {
    try { await page.goto(`http://127.0.0.1:${port}/producer.html`); break; }
    catch (error) { if (attempt===29) throw error; await new Promise(r=>setTimeout(r,100)); }
  }
  await page.waitForFunction(() => document.querySelector('#export-capability').textContent.length > 0);
  assert(await page.locator('#export').isDisabled());
  await page.locator('#recording').setInputFiles(video);
  await page.waitForFunction(() => document.querySelector('#source-badge').textContent === 'LOCAL FILE');
  await page.locator('#transcript').setInputFiles(transcript);
  await page.waitForFunction(() => !document.querySelector('#recommend').disabled);
  await page.locator('#recommend').click();
  assert.equal(await page.locator('.clip-card').count(), 5);
  await page.locator('#recommend').click();
  assert.equal(await page.locator('.clip-card').count(), 5, 'Repeated suggestions must not duplicate cuts');
  await page.locator('#clip-title').fill('<img src=x onerror=alert(1)> Real title');
  await page.locator('#clip-form button[type=submit]').click();
  assert.equal(await page.locator('.clip-card img').count(), 0, 'Titles must be treated as text');
  await page.locator('#clip-start').fill('25');
  await page.locator('#clip-end').fill('10');
  await page.locator('#approve').click();
  assert(await page.locator('#notice').evaluate(el => el.classList.contains('error')));
  await page.locator('#clip-start').fill('1.234');
  await page.locator('#clip-end').fill('4');
  await page.locator('#approve').click();
  assert.equal(await page.locator('.clip-card[aria-pressed=true] .clip-state').textContent(), 'approved');
  assert(await page.locator('#export').isEnabled());
  await page.locator('#clip-title').fill('An edited clip needs review');
  assert(await page.locator('#export').isDisabled());
  await page.locator('#clip-form button[type=submit]').click();
  assert.equal(await page.locator('.clip-card[aria-pressed=true] .clip-state').textContent(), 'To review');
  await page.locator('#recommend').click();
  assert.equal(await page.locator('.clip-card').count(), 5, 'Regenerating after a trim must not duplicate suggestion IDs');
  await page.locator('#reject').click();
  await page.locator('[data-filter=rejected]').click();
  assert.equal(await page.locator('.clip-card').count(), 1);
  await page.locator('#rescue').click();
  assert.equal(await page.locator('.clip-card').count(), 0);
  await page.locator('[data-filter=all]').click();
  assert.equal(await page.locator('.clip-card').count(), 5);
  await page.locator('#approve').click();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#download-project').click();
  const download = await downloadPromise;
  const backup = join(temp, 'backup.json');
  await download.saveAs(backup);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#source-badge').textContent === 'RECONNECT FILE');
  assert.equal(await page.locator('.clip-card').count(), 5);
  assert(await page.locator('#export').isDisabled());
  assert(await page.locator('#approve').isHidden());
  await page.locator('#recording').setInputFiles(video);
  await page.waitForFunction(() => document.querySelector('#source-badge').textContent === 'LOCAL FILE');
  assert.equal(await page.locator('.clip-card').count(), 5);
  assert(await page.locator('#export').isEnabled());
  await page.locator('#export').click();
  await page.locator('#cancel-export').click();
  await page.waitForFunction(() => document.querySelector('#export-status').textContent.includes('cancelled'));
  assert(await page.locator('#export').isEnabled());
  const clipDownloadPromise = page.waitForEvent('download');
  await page.locator('#export').click();
  const clipDownload = await clipDownloadPromise;
  assert(clipDownload.suggestedFilename().endsWith('.webm'));
  const clipFile = join(temp, 'rendered.webm');
  await clipDownload.saveAs(clipFile);
  assert.equal(readFileSync(clipFile).subarray(0, 4).toString('hex'), '1a45dfa3');
  await page.waitForFunction(() => !document.querySelector('#export').disabled);
  await page.locator('#recording').setInputFiles(join(temp, 'bad.mp4'));
  await page.waitForFunction(() => document.querySelector('#notice').classList.contains('error'));
  assert.equal(await page.locator('.clip-card').count(), 5, 'Invalid import must not destroy current project');
  assert.equal(await page.locator('#source-badge').textContent(), 'LOCAL FILE');
  await page.locator('#transcript').setInputFiles(join(temp,'bad.vtt'));
  await page.waitForFunction(() => document.querySelector('#notice').textContent.includes('cue') || document.querySelector('#notice').textContent.includes('end'));
  assert.equal(await page.locator('.clip-card').count(), 5);
  await page.locator('#clear-project').click();
  assert.equal(await page.locator('.clip-card').count(), 0);
  await page.locator('#project-import').setInputFiles(backup);
  await page.waitForFunction(() => document.querySelector('#source-badge').textContent === 'RECONNECT FILE');
  assert.equal(await page.locator('.clip-card').count(), 5);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(screenshots, 'studio-mobile.png'), fullPage: true });
  console.log('mobile dimensions', await page.evaluate(() => ({width:innerWidth, scroll:document.documentElement.scrollWidth, overflow:[...document.querySelectorAll('*')].filter(el=>el.getBoundingClientRect().right>innerWidth).map(el=>el.tagName+'.'+el.className)})));
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout must not overflow');
  await page.screenshot({ path: join(screenshots, 'studio-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.screenshot({ path: join(screenshots, 'studio-desktop.png'), fullPage: true });
  await page.locator('#recording').setInputFiles(video);
  await page.waitForFunction(() => document.querySelector('#source-badge').textContent === 'LOCAL FILE');
  await page.locator('#add-clip').click();
  assert.equal(await page.locator('.clip-card').count(), 6);
  assert.equal(await page.locator('#clip-origin').textContent(), 'MANUAL CUT');
  await page.locator('#clip-form button[type=submit]').click();
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError'); }; });
  await page.locator('#clip-title').fill('Storage failure must stay visible');
  await page.locator('#clip-form button[type=submit]').click();
  assert(await page.locator('#storage-warning').isVisible());
  await page.locator('#approve').click();
  assert(await page.locator('#storage-warning').isVisible());
  assert.deepEqual(errors, []);
  console.log(`PASS: import, five recommendations, edited-cut dedupe, text safety, fractional trims, approval invalidation, reject/rescue, persistence, reconnect, invalid import recovery, backup restore, manual cuts, render/cancel/download, storage failure warnings, mobile layout. Screenshots: ${screenshots}`);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); server.kill(); });
