create table if not exists public.viewer_events (
  id bigint generated by default as identity primary key,
  session_id text not null check (char_length(session_id) between 1 and 120),
  stream_id text not null check (char_length(stream_id) between 1 and 100),
  event_type text not null,
  playback_position double precision not null default 0,
  occurred_at timestamptz not null default now(),
  details jsonb not null default '{}'::jsonb
);

create index if not exists viewer_events_stream_time_idx
  on public.viewer_events (stream_id, occurred_at desc);
create index if not exists viewer_events_session_time_idx
  on public.viewer_events (session_id, occurred_at desc);

alter table public.viewer_events enable row level security;

